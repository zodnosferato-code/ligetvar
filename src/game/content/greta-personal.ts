export function rewriteGretaPersonal(original:Scene):Scene {
 const s=structuredClone(original),p=s.id==='greta_3'?'date':'after';
 const title=message(key(p+'.title'));s.title=title.text;s.titleKey=title.textKey;s.journal=storedMessage(key(p+'.journal'));
 const originalChoices=original.lines.find(l=>l.id==='line_4')!.choices!;
 s.lines=graphs[p].map(([id,speaker,stage,next]):Line=>({id,speaker,stage,...message(key(p+'.'+id)),expression:speaker==='greta'?'amused':'neutral',...(next?{next}:{})}));
 const stage=(id:string,location:SceneStage['location'],proximity:SceneStage['proximity']='apart'):SceneStage=>({label:storedMessage(key('stage.'+id)),location,background:location,participants:['marton','greta'],proximity});
 const stages={lake:stage('lake','bekas'),beside:stage('beside','bekas','beside'),courtyard:stage('courtyard','courtyard'),close:stage('close','courtyard','close'),room:stage('room','apartment'),private:stage('private','apartment','close')};
 const used=new Set(s.lines.map(l=>l.stage));s.stages=Object.fromEntries(Object.entries(stages).filter(([id])=>used.has(id)));
 for(const [id,choices] of Object.entries(menus[p]))s.lines.find(l=>l.id===id)!.choices=choices.map(([cid,next]):Choice=>{
  const c:Choice={id:cid,...message(key(p+'.'+id+'.'+cid)),reaction:'',next};
  if(id==='line_4')c.effect=originalChoices.find(x=>x.id===cid)!.effect;
  if(p==='date'&&id==='hand_offer')c.effect={decisions:[cid==='hand'?'greta_date_hand':'greta_date_slow']};
  if(p==='date'&&id==='bench'&&cid==='kiss'){c.localRequires=['greta_date_hand'];c.effect={decisions:['greta_date_romantic_kiss']};}
  if(p==='after'&&id==='future'&&cid!=='food')c.requires={decisions:[cid==='ordinary'?'greta_future_ordinary':'greta_future_ask']};
  return c;
 });
 for(const l of s.lines)if(l.speaker==='greta'&&(l.id.startsWith('withdraw')||l.id==='line_3'&&p==='after'))l.expression='vulnerable';
 if(p==='after'){
  const intimate={anyOf:[{decisions:['greta_midpoint_intimate']},{decisions:['greta_dance_intimate']}]};
  const recall=(id:string,next:string,requires:Choice['requires']):Choice=>({id,next,requires,...message(key('after.history.'+id)),reaction:''});
  s.lines.find(l=>l.id==='future')!.choices!.push(recall('remember','history',{scenes:['greta_company']}));
  const rows:Row[]=[
   ['history','greta','beside',null],
   ['sketch_memory','marton','beside','sketch_reply'],['sketch_reply','greta','beside','pour'],
   ['dance_memory','marton','beside','dance_reply'],['dance_reply','greta','beside','pour'],
   ['private_memory','marton','beside','private_reply'],['private_reply','greta','beside','pour'],
   ['company_memory','marton','beside','company_reply'],['company_reply','greta','beside','pour'],
   ['again','greta','private','fade']
  ];
  s.lines.push(...rows.map(([id,speaker,stage,next]):Line=>({id,speaker,stage,...message(key('after.'+id)),expression:speaker==='greta'?'affectionate':'neutral',...(next?{next}:{})})));
  s.lines.find(l=>l.id==='history')!.choices=[
   recall('sketch','sketch_memory',{scenes:['greta_sketch']}),
   recall('dance','dance_memory',{anyOf:[{decisions:['greta_dance_steps']},{decisions:['greta_dance_rhythm']}]}),
   recall('private','private_memory',intimate),
   recall('company','company_memory',undefined)
  ];
  const choices=s.lines.find(l=>l.id==='intimacy')!.choices!;
  choices.find(c=>c.id==='intimate')!.requires={notDecisions:['greta_midpoint_intimate','greta_dance_intimate']};
  choices.splice(1,0,{id:'again',next:'again',requires:intimate,...message(key('after.intimacy.again')),reaction:''});
 }
 return s;
}
